local ok, value = pcall(function(a, b) return a + b end, 20, 22)
assert(ok and value == 42)
local function expect_error(fn, text)
  local success, message = pcall(fn)
  assert(not success and type(message) == "string")
  assert(string.find(message, text, 1, true))
end
expect_error(function() error("intentional failure") end, "intentional failure")
expect_error(function() local t = {}; local key; t[key] = 1 end, "table index is nil")
expect_error(function() local t = {}; t[0 / 0] = 1 end, "table index is NaN")
expect_error(function() local t; return t.field end, "attempt to index")
local chunk, message = loadstring("local = syntax")
assert(chunk == nil and type(message) == "string")
io.write("errors: pcall nil NaN indexing loadstring\n")
